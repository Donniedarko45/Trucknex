#!/usr/bin/env python3
"""Simplify India's official-boundary outline into src/components/network/indiaOutline.ts.

Source: datameet/maps `Country/india-composite.geojson` (CC-0), which follows the
official boundary of India as per the Survey of India. Download it, then run:

    curl -L -o /tmp/india-composite.geojson \
      https://raw.githubusercontent.com/datameet/maps/master/Country/india-composite.geojson
    python3 scripts/build_india_outline.py /tmp/india-composite.geojson

Only the mainland ring is kept; island groups are below the map's resolution.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/components/network/indiaOutline.ts"
TOLERANCE_DEG = 0.06  # ≈1 map unit at the homepage scale


def simplify(points: list[tuple[float, float]], tolerance: float) -> list[tuple[float, float]]:
    """Iterative Douglas–Peucker on lon/lat pairs, longitude scaled by cos(latitude)."""
    scale = math.cos(math.radians(22))

    def distance(p, a, b):
        ax, ay, bx, by, px, py = a[0] * scale, a[1], b[0] * scale, b[1], p[0] * scale, p[1]
        dx, dy = bx - ax, by - ay
        if dx == dy == 0:
            return math.hypot(px - ax, py - ay)
        t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
        return math.hypot(px - ax - t * dx, py - ay - t * dy)

    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        start, end = stack.pop()
        index, worst = 0, 0.0
        for i in range(start + 1, end):
            d = distance(points[i], points[start], points[end])
            if d > worst:
                index, worst = i, d
        if worst > tolerance:
            keep[index] = True
            stack += [(start, index), (index, end)]
    return [p for p, k in zip(points, keep) if k]


def main() -> None:
    source = Path(sys.argv[1])
    geometry = json.loads(source.read_text())["features"][0]["geometry"]
    polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    mainland = max((polygon[0] for polygon in polygons), key=len)
    outline = simplify([(lon, lat) for lon, lat in mainland], TOLERANCE_DEG)
    pairs = ",".join(f"[{lon:.2f},{lat:.2f}]" for lon, lat in outline)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "// Generated by scripts/build_india_outline.py — do not edit by hand.\n"
        "// Official boundary of India (Survey of India) via datameet/maps\n"
        "// Country/india-composite.geojson, CC-0. Mainland only, simplified.\n"
        f"export const INDIA_OUTLINE: readonly [lon: number, lat: number][] = [{pairs}];\n"
    )
    print(f"{len(mainland)} → {len(outline)} points written to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
